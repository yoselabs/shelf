def _verdict(repo: Repo, check_id: str, *, audit: bool = True) -> tuple[Verdict, str]:
    rows = {r.id: r for r in run(repo.root, concern="gate", audit=audit, env=repo.env).rows}
    return rows[check_id].verdict, rows[check_id].evidence


