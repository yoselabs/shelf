"""Living ADRs: one file per decision topic, frontmatter on top, history inside; and their index.

An ADR is rewritten when its decision changes; the old decision and why it was dropped move into the
file's `## History`. Agents read only `docs/adr/INDEX.md`, generated from the frontmatter: one line per
decision in force. The files are opened only to challenge or change a decision.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from pathlib import Path

FOLDER = "docs/adr"
INDEX = "INDEX.md"
REQUIRED = ("id", "title", "statement", "concerns", "status", "decided_by", "updated")
STATUSES = ("proposed", "accepted", "superseded", "rejected")
_IN_FORCE = "accepted"
_FILE = re.compile(r"^(\d{4})-[a-z0-9-]+\.md$")
_DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
_HISTORY = re.compile(r"^## History\s*$", re.MULTILINE)
# The index line is what agents load; a statement longer than this stops being one line of a list.
STATEMENT_MAX = 200


@dataclass(frozen=True)
class Adr:
    """One ADR file's frontmatter, as written."""

    name: str
    fields: dict[str, str]

    @property
    def concerns(self) -> list[str]:
        """The `concerns: [a, b]` list."""
        return [c.strip() for c in self.fields.get("concerns", "").strip("[]").split(",") if c.strip()]


def files(repo: Path) -> list[Path]:
    """The ADR files in the repo's folder, by name; the index and a README are not ADRs."""
    folder = repo / FOLDER
    if not folder.is_dir():
        return []
    return sorted(p for p in folder.glob("*.md") if p.name not in {INDEX, "README.md"})


def parse(path: Path) -> Adr | None:
    """The frontmatter of `path`; None when the file does not open with a `---` block."""
    text = path.read_text(errors="replace")
    if not text.startswith("---\n") or "\n---" not in text[4:]:
        return None
    block = text[4 : text.index("\n---", 4)]
    fields = {}
    for line in block.splitlines():
        key, sep, value = line.partition(":")
        if sep and not line.startswith((" ", "-")):
            fields[key.strip()] = value.strip()
    return Adr(path.name, fields)


def problems(path: Path) -> list[str]:
    """What is wrong with one ADR file, each as a short phrase; empty when it is sound."""
    numbered = _FILE.match(path.name)
    if numbered is None:
        return ["name is not NNNN-slug.md"]
    found = parse(path)
    if found is None:
        return ["no frontmatter"]
    fields = found.fields
    out = [f"no {key}" for key in REQUIRED if not fields.get(key)]
    if fields.get("id") and fields["id"] != numbered.group(1):
        out.append(f"id {fields['id']} differs from the file number")
    if fields.get("status") and fields["status"] not in STATUSES:
        out.append(f"status {fields['status']} is not one of {', '.join(STATUSES)}")
    if len(fields.get("statement", "")) > STATEMENT_MAX:
        out.append(f"statement over {STATEMENT_MAX} characters")
    if fields.get("updated") and not _DATE.match(fields["updated"]):
        out.append("updated is not YYYY-MM-DD")
    if not _HISTORY.search(path.read_text(errors="replace")):
        out.append("no ## History")
    return out


_HEADER = """# Decisions

Generated by `blueprint adr-index`; never edit by hand. Each line is a decision in force.
This index is what you need to work. Open an ADR file only to challenge or change its decision:
the file holds the reasons, the rejected options and the history.
"""


def index(repo: Path) -> str:
    """The INDEX.md text: accepted decisions grouped by their first concern, then proposed ones."""
    parsed = [a for a in (parse(p) for p in files(repo)) if a is not None]
    groups: dict[str, list[str]] = {}
    proposed: list[str] = []
    for found in parsed:
        line = f"- [{found.fields.get('id', '?')}]({found.name}) **{found.fields.get('title', '')}**: {found.fields.get('statement', '')}"
        status = found.fields.get("status")
        if status == _IN_FORCE:
            groups.setdefault((found.concerns or ["general"])[0], []).append(line)
        elif status == "proposed":
            proposed.append(line)
    parts = [_HEADER]
    parts += [f"## {concern}\n\n" + "\n".join(lines) + "\n" for concern, lines in sorted(groups.items())]
    if proposed:
        parts.append("## Proposed, not in force\n\n" + "\n".join(proposed) + "\n")
    return "\n".join(parts)
